-- Auction bidding, settlement, watchlists, second-chance offers, and portfolio tracking.

-- 1. Expand auction status check constraint to include new finalization states
ALTER TABLE auctions DROP CONSTRAINT IF EXISTS auctions_status_check;
ALTER TABLE auctions ADD CONSTRAINT auctions_status_check CHECK (status IN (
    'DRAFT', 'SCHEDULED', 'ACTIVE', 'ENDED', 'AWAITING_PAYMENT', 'COMPLETED', 'CANCELLED',
    'BUYOUT_COMPLETED', 'RESERVE_NOT_MET', 'UNSOLD_NO_BIDS', 'DEFAULTED'
));

-- 2. Add settlement, financial snapshot, and winner fields to auctions
ALTER TABLE auctions
    ADD COLUMN IF NOT EXISTS leading_bidder_id BIGINT REFERENCES users(id),
    ADD COLUMN IF NOT EXISTS winner_id BIGINT REFERENCES users(id),
    ADD COLUMN IF NOT EXISTS winning_bid NUMERIC(12, 2),
    ADD COLUMN IF NOT EXISTS is_reserve_met BOOLEAN NOT NULL DEFAULT FALSE,
    ADD COLUMN IF NOT EXISTS order_id BIGINT REFERENCES orders(id),
    ADD COLUMN IF NOT EXISTS payment_deadline TIMESTAMPTZ,
    ADD COLUMN IF NOT EXISTS platform_fee_rate NUMERIC(5, 4) NOT NULL DEFAULT 0.0500,
    ADD COLUMN IF NOT EXISTS platform_fee_amount NUMERIC(12, 2) NOT NULL DEFAULT 0.00,
    ADD COLUMN IF NOT EXISTS seller_net_amount NUMERIC(12, 2) NOT NULL DEFAULT 0.00,
    ADD COLUMN IF NOT EXISTS cost_basis NUMERIC(12, 2) NOT NULL DEFAULT 0.00;

CREATE INDEX IF NOT EXISTS idx_auctions_winner ON auctions(winner_id);
CREATE INDEX IF NOT EXISTS idx_auctions_status_filter ON auctions(status, end_at);

-- 3. Table: auction_bids (Bid History, Manual Bids, Proxy Bids, Buyouts)
CREATE TABLE IF NOT EXISTS auction_bids (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    auction_id BIGINT NOT NULL REFERENCES auctions(id) ON DELETE CASCADE,
    bidder_id BIGINT NOT NULL REFERENCES users(id),
    bid_amount NUMERIC(12, 2) NOT NULL CHECK (bid_amount > 0),
    max_bid_amount NUMERIC(12, 2),
    bid_type VARCHAR(20) NOT NULL CHECK (bid_type IN ('MANUAL', 'PROXY', 'BUYOUT')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_auction_bids_auction_rank ON auction_bids(auction_id, bid_amount DESC, created_at ASC);
CREATE INDEX IF NOT EXISTS idx_auction_bids_bidder ON auction_bids(bidder_id, created_at DESC);

-- 4. Table: auction_watchlists
CREATE TABLE IF NOT EXISTS auction_watchlists (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    auction_id BIGINT NOT NULL REFERENCES auctions(id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    notified_1h BOOLEAN NOT NULL DEFAULT FALSE,
    notified_15m BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_auction_watchlist UNIQUE (user_id, auction_id)
);

CREATE INDEX IF NOT EXISTS idx_auction_watchlist_auction ON auction_watchlists(auction_id);
CREATE INDEX IF NOT EXISTS idx_auction_watchlist_user ON auction_watchlists(user_id, created_at DESC);

-- 5. Table: auction_second_chance_offers
CREATE TABLE IF NOT EXISTS auction_second_chance_offers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    auction_id BIGINT NOT NULL REFERENCES auctions(id) ON DELETE CASCADE,
    bidder_id BIGINT NOT NULL REFERENCES users(id),
    offer_price NUMERIC(12, 2) NOT NULL CHECK (offer_price > 0),
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING', 'ACCEPTED', 'REJECTED', 'EXPIRED')),
    expires_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    responded_at TIMESTAMPTZ
);

CREATE INDEX IF NOT EXISTS idx_auction_second_chance_bidder ON auction_second_chance_offers(bidder_id, status);
CREATE INDEX IF NOT EXISTS idx_auction_second_chance_auction ON auction_second_chance_offers(auction_id);

-- 6. Add default penalties to users
ALTER TABLE users
    ADD COLUMN IF NOT EXISTS auction_strikes INTEGER NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS auction_banned_until TIMESTAMPTZ;

-- 7. Add order_type to orders and update order status constraint
ALTER TABLE orders
    ADD COLUMN IF NOT EXISTS order_type VARCHAR(20) NOT NULL DEFAULT 'DIRECT';

ALTER TABLE orders DROP CONSTRAINT IF EXISTS orders_order_type_check;
ALTER TABLE orders ADD CONSTRAINT orders_order_type_check CHECK (order_type IN ('DIRECT', 'AUCTION'));

ALTER TABLE orders DROP CONSTRAINT IF EXISTS orders_status_check;
ALTER TABLE orders ADD CONSTRAINT orders_status_check
    CHECK (status IN ('PENDING', 'CONFIRMED', 'SENT', 'FULFILLED', 'CANCELLED', 'DEFAULTED'));

-- 8. Add provenance and auction trophies to collection_items
ALTER TABLE collection_items
    ADD COLUMN IF NOT EXISTS provenance VARCHAR(100),
    ADD COLUMN IF NOT EXISTS is_auction_won BOOLEAN NOT NULL DEFAULT FALSE,
    ADD COLUMN IF NOT EXISTS grading_company VARCHAR(10),
    ADD COLUMN IF NOT EXISTS grade VARCHAR(30),
    ADD COLUMN IF NOT EXISTS cert_number VARCHAR(100),
    ADD COLUMN IF NOT EXISTS image_front_url VARCHAR(500),
    ADD COLUMN IF NOT EXISTS image_back_url VARCHAR(500);

-- 9. Expand notification types
ALTER TABLE notifications DROP CONSTRAINT IF EXISTS chk_notifications_type;
ALTER TABLE notifications ADD CONSTRAINT chk_notifications_type CHECK (notification_type IN (
    'ORDER_RESERVED', 'ORDER_STATUS_CHANGED',
    'SELLER_APPLICATION_SUBMITTED', 'SELLER_APPLICATION_APPROVED', 'SELLER_APPLICATION_REJECTED',
    'AUCTION_CANCELLATION_SUBMITTED', 'AUCTION_CANCELLATION_DECIDED',
    'AUCTION_OUTBID', 'AUCTION_WON', 'AUCTION_ENDED_SELLER',
    'AUCTION_WATCHLIST_ENDING', 'AUCTION_SECOND_CHANCE', 'AUCTION_DEFAULTED_WARNING'
));

CREATE TABLE auction_payment_proofs (
    order_id BIGINT PRIMARY KEY REFERENCES orders(id) ON DELETE CASCADE,
    content_type VARCHAR(30) NOT NULL,
    content BYTEA NOT NULL,
    submitted_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE auction_commission_policy (
    id INTEGER PRIMARY KEY CHECK (id = 1),
    rate NUMERIC(5,4) NOT NULL CHECK (rate BETWEEN 0 AND 1),
    minimum_fee NUMERIC(12,2) NOT NULL CHECK (minimum_fee >= 0)
);
