ALTER TABLE users ADD COLUMN IF NOT EXISTS auth_version BIGINT NOT NULL DEFAULT 0;

CREATE TABLE IF NOT EXISTS password_reset_tokens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL UNIQUE REFERENCES users(id) ON DELETE CASCADE,
    token_hash VARCHAR(64) NOT NULL UNIQUE,
    created_at TIMESTAMP NOT NULL,
    expires_at TIMESTAMP NOT NULL
);

ALTER TABLE notification_email_outbox ALTER COLUMN notification_id DROP NOT NULL;
ALTER TABLE notification_email_outbox ADD COLUMN IF NOT EXISTS sensitive BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE notification_email_outbox ADD COLUMN IF NOT EXISTS expires_at TIMESTAMP;

-- Existing installations may contain the prerelease password schema. Reject
-- incompatible definitions instead of silently accepting IF NOT EXISTS drift.
DO $$
BEGIN
    IF (SELECT count(*) FROM information_schema.columns
        WHERE table_schema = current_schema() AND (
            (table_name = 'users' AND column_name = 'auth_version' AND data_type = 'bigint' AND is_nullable = 'NO') OR
            (table_name = 'password_reset_tokens' AND column_name IN ('id', 'user_id') AND data_type = 'bigint' AND is_nullable = 'NO') OR
            (table_name = 'password_reset_tokens' AND column_name = 'token_hash' AND data_type = 'character varying' AND character_maximum_length = 64 AND is_nullable = 'NO') OR
            (table_name = 'password_reset_tokens' AND column_name IN ('created_at', 'expires_at') AND data_type = 'timestamp without time zone' AND is_nullable = 'NO') OR
            (table_name = 'notification_email_outbox' AND column_name = 'sensitive' AND data_type = 'boolean' AND is_nullable = 'NO') OR
            (table_name = 'notification_email_outbox' AND column_name = 'expires_at' AND data_type = 'timestamp without time zone' AND is_nullable = 'YES') OR
            (table_name = 'notification_email_outbox' AND column_name = 'notification_id' AND is_nullable = 'YES')
        )) <> 9 THEN
        RAISE EXCEPTION 'Incompatible password recovery schema';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid = 'password_reset_tokens'::regclass AND contype = 'p')
       OR NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid = 'password_reset_tokens'::regclass AND contype = 'u' AND pg_get_constraintdef(oid) = 'UNIQUE (user_id)')
       OR NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid = 'password_reset_tokens'::regclass AND contype = 'u' AND pg_get_constraintdef(oid) = 'UNIQUE (token_hash)')
       OR NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid = 'password_reset_tokens'::regclass AND contype = 'f' AND confrelid = 'users'::regclass AND confdeltype = 'c') THEN
        RAISE EXCEPTION 'Incompatible password recovery constraints';
    END IF;
END $$;
