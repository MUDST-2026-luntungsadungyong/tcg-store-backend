CREATE TABLE card_search_names (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    card_id VARCHAR(100) NOT NULL REFERENCES global_cards(id) ON DELETE CASCADE,
    language VARCHAR(2) NOT NULL CHECK (language IN ('th', 'en')),
    name VARCHAR(255) NOT NULL,
    search_name VARCHAR(255) NOT NULL CHECK (length(search_name) > 0),
    source VARCHAR(255) NOT NULL,
    CONSTRAINT uq_card_search_name UNIQUE (card_id, language, search_name)
);
