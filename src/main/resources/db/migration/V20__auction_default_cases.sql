CREATE TABLE auction_default_cases (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 auction_id BIGINT NOT NULL REFERENCES auctions(id), order_id BIGINT NOT NULL UNIQUE REFERENCES orders(id),
 order_number VARCHAR(255) NOT NULL, buyer_id BIGINT NOT NULL REFERENCES users(id), seller_id BIGINT NOT NULL REFERENCES users(id),
 report_reason VARCHAR(2000) NOT NULL, status VARCHAR(20) NOT NULL CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED', 'REVERSED')),
 created_at TIMESTAMP WITH TIME ZONE NOT NULL, decided_at TIMESTAMP WITH TIME ZONE, decision_reason VARCHAR(2000)
);
CREATE INDEX idx_default_cases_buyer ON auction_default_cases(buyer_id, status);
CREATE INDEX idx_default_cases_seller ON auction_default_cases(seller_id);
CREATE TABLE auction_default_decisions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 case_id BIGINT NOT NULL REFERENCES auction_default_cases(id), admin_id BIGINT NOT NULL REFERENCES users(id),
 action VARCHAR(20) NOT NULL CHECK (action IN ('APPROVED', 'REJECTED', 'REVERSED')), reason VARCHAR(2000) NOT NULL, created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_default_decisions_case ON auction_default_decisions(case_id, id);
