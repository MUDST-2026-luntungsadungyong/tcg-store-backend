-- Auction reservations are separate from checkout reservations and share the same stock row.
ALTER TABLE local_cards ADD COLUMN auction_reserved INTEGER NOT NULL DEFAULT 0;
ALTER TABLE local_cards ADD CONSTRAINT chk_local_cards_auction_reserved
    CHECK (auction_reserved >= 0 AND (auction_reserved = 0 OR auction_reserved <= on_hand - reserved));

CREATE TABLE auctions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seller_id BIGINT NOT NULL REFERENCES users(id),
    product_id BIGINT REFERENCES local_cards(id) ON DELETE SET NULL,
    creation_key VARCHAR(100),
    status VARCHAR(24) NOT NULL CHECK (status IN (
        'DRAFT', 'SCHEDULED', 'ACTIVE', 'ENDED', 'AWAITING_PAYMENT', 'COMPLETED', 'CANCELLED'
    )),
    card_id VARCHAR(100),
    card_name VARCHAR(255),
    set_name VARCHAR(255),
    image_url VARCHAR(500),
    condition VARCHAR(50),
    grading_company VARCHAR(10),
    grade VARCHAR(30),
    cert_number VARCHAR(100),
    start_price NUMERIC(12, 2),
    reserve_price NUMERIC(12, 2),
    buy_it_now_price NUMERIC(12, 2),
    start_mode VARCHAR(12) CHECK (start_mode IN ('NOW', 'SCHEDULED')),
    start_at TIMESTAMPTZ,
    end_at TIMESTAMPTZ,
    duration_hours INTEGER CHECK (duration_hours IN (24, 72, 120, 168)),
    bid_count INTEGER NOT NULL DEFAULT 0 CHECK (bid_count >= 0),
    highest_bid NUMERIC(12, 2),
    stock_held BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uq_auctions_seller_creation_key UNIQUE (seller_id, creation_key),
    CONSTRAINT chk_auctions_pricing CHECK (
        (start_price IS NULL OR start_price > 0)
        AND (reserve_price IS NULL OR (reserve_price > 0 AND (start_price IS NULL OR reserve_price >= start_price)))
        AND (buy_it_now_price IS NULL OR (buy_it_now_price > 0
            AND (start_price IS NULL OR buy_it_now_price > start_price)
            AND (reserve_price IS NULL OR buy_it_now_price > reserve_price)))
    ),
    CONSTRAINT chk_auctions_published CHECK (status = 'DRAFT' OR (
        card_id IS NOT NULL AND card_name IS NOT NULL AND condition IS NOT NULL
        AND start_price IS NOT NULL AND start_mode IS NOT NULL AND duration_hours IS NOT NULL
        AND start_at IS NOT NULL AND end_at IS NOT NULL AND end_at > start_at
    )),
    CONSTRAINT chk_auctions_hold CHECK (
        (NOT stock_held OR product_id IS NOT NULL)
        AND (status NOT IN ('SCHEDULED', 'ACTIVE') OR stock_held)
    )
);
CREATE INDEX idx_auctions_seller_updated ON auctions(seller_id, updated_at DESC, id DESC);
CREATE INDEX idx_auctions_scheduled_start ON auctions(start_at, id) WHERE status = 'SCHEDULED';
CREATE INDEX idx_auctions_active_end ON auctions(end_at, id) WHERE status = 'ACTIVE';
CREATE INDEX idx_auctions_product ON auctions(product_id);

CREATE TABLE auction_photos (
    auction_id BIGINT NOT NULL REFERENCES auctions(id) ON DELETE CASCADE,
    side VARCHAR(5) NOT NULL CHECK (side IN ('FRONT', 'BACK')),
    content_type VARCHAR(30) NOT NULL,
    content BYTEA NOT NULL CHECK (octet_length(content) BETWEEN 1 AND 5242880),
    PRIMARY KEY (auction_id, side)
);

CREATE TABLE auction_cancellation_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    auction_id BIGINT NOT NULL REFERENCES auctions(id),
    status VARCHAR(20) NOT NULL CHECK (status IN ('PENDING_REVIEW', 'APPROVED', 'REJECTED')),
    reason VARCHAR(1000) NOT NULL,
    decision_reason VARCHAR(1000),
    reviewed_by BIGINT REFERENCES users(id),
    created_at TIMESTAMPTZ NOT NULL,
    reviewed_at TIMESTAMPTZ
);
CREATE UNIQUE INDEX uq_auction_pending_cancellation ON auction_cancellation_requests(auction_id)
    WHERE status = 'PENDING_REVIEW';
CREATE INDEX idx_auction_cancellations_review ON auction_cancellation_requests(status, created_at, id);
CREATE INDEX idx_auction_cancellations_auction ON auction_cancellation_requests(auction_id, id DESC);

CREATE TABLE auction_cancellation_evidence (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id BIGINT NOT NULL REFERENCES auction_cancellation_requests(id) ON DELETE CASCADE,
    file_name VARCHAR(200) NOT NULL,
    content_type VARCHAR(30) NOT NULL,
    content BYTEA NOT NULL CHECK (octet_length(content) BETWEEN 1 AND 5242880)
);
CREATE INDEX idx_auction_cancellation_evidence_request ON auction_cancellation_evidence(request_id, id);

ALTER TABLE notifications DROP CONSTRAINT IF EXISTS notifications_notification_type_check;
ALTER TABLE notifications DROP CONSTRAINT IF EXISTS chk_notifications_type;
ALTER TABLE notifications ADD CONSTRAINT chk_notifications_type CHECK (notification_type IN (
    'ORDER_RESERVED', 'ORDER_STATUS_CHANGED',
    'SELLER_APPLICATION_SUBMITTED', 'SELLER_APPLICATION_APPROVED', 'SELLER_APPLICATION_REJECTED',
    'AUCTION_CANCELLATION_SUBMITTED', 'AUCTION_CANCELLATION_DECIDED'
));
